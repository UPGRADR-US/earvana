// Run the development-only fresh-session request before App imports its usage observer.
import "./lib/freeviewTestBootstrap";
import { createRoot } from "react-dom/client";
import { Capacitor } from "@capacitor/core";
import App from "./App";
import "./index.css";

// Detect Android phone (excluding tablets) to apply navigation-bar offset
function detectAndroidPhone() {
  if (typeof document === "undefined") return;
  try {
    const ua = navigator.userAgent || "";
    const isAndroid = (Capacitor.isNativePlatform() && Capacitor.getPlatform() === "android") || /Android/i.test(ua);
    const smallestDim = Math.min(window.screen.width || 0, window.screen.height || 0);
    const isTablet = smallestDim >= 600 || (!/Mobile/i.test(ua) && /Android/i.test(ua) && !/AndroidPhone/i.test(ua));
    if (isAndroid && !isTablet) {
      document.documentElement.classList.add("android-phone");
    }
  } catch {}
}
detectAndroidPhone();

// SW is generated by vite-plugin-pwa at build time only — skip in dev to avoid
// a 404 MIME-type warning when public/sw.js is absent.
if ("serviceWorker" in navigator && import.meta.env.PROD) {
  window.addEventListener("load", () => {
    navigator.serviceWorker.register(import.meta.env.BASE_URL + "sw.js").catch(() => {});
  });
}

// Opt-in local visual test: enable before mounting any playback controls.
// Production builds and native apps never use this URL switch.
async function mount() {
  if (import.meta.env.DEV && !Capacitor.isNativePlatform() &&
      new URLSearchParams(window.location.search).get("freeviewTest") === "1") {
    const { configureDevelopmentFreeview } = await import("./lib/developmentFreeview");
    await configureDevelopmentFreeview(true);
  }
  createRoot(document.getElementById("root")!).render(<App />);
}
void mount();
